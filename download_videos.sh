echo "Directory is ready."
echo ""

# Loop through the files and download them
for file in "${FILES[@]}"; do
    # Define the full path for the local file
    local_file_path="$TARGET_DIR/$file"
    
    # Check if the file already exists
    if [ -f "$local_file_path" ]; then
        echo "☑️  Skipping '$file' (already exists)."
    else
        # Construct the full URL
        full_url="$BASE_URL/$file"
        
        echo "⬇️  Downloading '$file'..."
        # Use wget to download the file into the target directory
        # -P specifies the directory prefix
        # -q makes it quiet
        wget -q -P "$TARGET_DIR" "$full_url"
        
        # Check if the download was successful
        if [ $? -eq 0 ]; then
            echo "✅  Successfully downloaded '$file'."
        else
            echo "❌  Failed to download '$file' from '$full_url'."
        fi
    fi
done

